async function get(path: string): Promise<string> {
	const response = await fetch(`${RAW}/${path}`);
	if (!response.ok) throw new Error(`${path} → ${response.status}`);
	return response.text();
}

function key(value: string): string {
	return JSON.stringify(value);
}

function quote(value: string): string {
	return `\`${value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;
}

function catalog(source: string): Record<string, { fileExtensions?: string[]; fileNames?: string[] }> {
	const start = source.indexOf("const fileIcons");
	if (start < 0) throw new Error("fileIcons is gone from the upstream source");
	const end = source.indexOf("\nconst ", start + 10);
	const object = source.slice(start, end).replace("const fileIcons: FileIcons =", "const fileIcons =");
	const evaluate = new Function(`${object}\nreturn fileIcons;`) as () => Record<string, { fileExtensions?: string[]; fileNames?: string[] }>;
	return evaluate();
}

function table(rows: readonly (readonly [string, string])[]): string {
	const lines = [...rows].sort((left, right) => left[0].localeCompare(right[0])).map(([name, value]) => `\t${key(name)}: ${quote(value)},`);
	return lines.join("\n");
}

async function main(): Promise<void> {
	await mkdir(OUT, { recursive: true });
	const glyphs: [string, string][] = [];
	for (const id of IDS) {
		const svg = (await get(`icons/css-variables/${id}.svg`)).replaceAll("var(--vscode-ctp-", "var(--ctp-").trim();
		glyphs.push([id, svg.replace(/\n\t?/g, "").replace(/>\s+</g, "><")]);
	}
	const map = catalog(await get("src/defaults/fileIcons.ts"));
	const extensions = new Map<string, string>();
	const names = new Map<string, string>();
	for (const id of IDS) {
		const entry = map[id];
		if (entry === undefined) continue;
		for (const extension of entry.fileExtensions ?? []) if (!extensions.has(extension.toLowerCase())) extensions.set(extension.toLowerCase(), id);
		for (const name of entry.fileNames ?? []) if (!names.has(name.toLowerCase())) names.set(name.toLowerCase(), id);
	}
	await writeFile(
		join(OUT, "glyphs.ts"),
		`// Generated by scripts/vendor-icons.ts from catppuccin/vscode-icons ${TAG} (MIT). Do not edit.\nexport const GLYPHS: Readonly<Record<string, string>> = {\n${table(glyphs)}\n};\n`,
	);
	await writeFile(
		join(OUT, "catalog.ts"),
		`// Generated by scripts/vendor-icons.ts from catppuccin/vscode-icons ${TAG} (MIT). Do not edit.\nexport const EXTENSIONS: Readonly<Record<string, string>> = {\n${table([...extensions])}\n};\n\nexport const NAMES: Readonly<Record<string, string>> = {\n${table([...names])}\n};\n`,
	);
	await writeFile(join(OUT, "LICENSE"), await get("LICENSE"));
	const bytes = glyphs.reduce((total, [, svg]) => total + Buffer.byteLength(svg), 0);
	console.log(`[icons] ${glyphs.length} glyphs, ${extensions.size} extensions, ${names.size} names, ${(bytes / 1024).toFixed(1)} KB → ${OUT}`);
	console.log("[icons] run `bun run format` before committing");
}

await main();
